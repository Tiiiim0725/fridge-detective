#!/usr/bin/env node

const fs = require('fs')
const path = require('path')

const DEFAULT_SEED_PATH = path.join('supabase', 'seeds', 'recipe_seed_v0.2.sql')
const DEFAULT_OUT_DIR = path.join('supabase', '.temp', 'recipe-image-import')
const DEFAULT_BUCKET = 'recipe-images'
const DEFAULT_PREFIX = 'cards'

function readArg(name, fallback = null) {
  const index = process.argv.indexOf(name)
  if (index >= 0 && process.argv[index + 1]) {
    return process.argv[index + 1]
  }
  return fallback
}

function requireArg(name) {
  const value = readArg(name)
  if (!value) {
    throw new Error(`Missing required argument: ${name}`)
  }
  return value
}

function escapeSql(value) {
  return value.replace(/'/g, "''")
}

function parseEnvFile(envPath) {
  if (!fs.existsSync(envPath)) {
    return {}
  }

  const env = {}
  const lines = fs.readFileSync(envPath, 'utf8').split(/\r?\n/)
  for (const line of lines) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) {
      continue
    }
    const equalsIndex = trimmed.indexOf('=')
    if (equalsIndex <= 0) {
      continue
    }
    env[trimmed.slice(0, equalsIndex)] = trimmed.slice(equalsIndex + 1)
  }
  return env
}

function parseRecipes(seedPath) {
  const sql = fs.readFileSync(seedPath, 'utf8')
  const start = sql.indexOf('insert into public.recipes')
  const end = sql.indexOf('on conflict (recipe_key)', start)

  if (start < 0 || end < 0) {
    throw new Error(`Could not find public.recipes insert block in ${seedPath}`)
  }

  const block = sql.slice(start, end)
  const recipes = []
  const linePattern = /^\s*\('([^']+)'\s*,\s*'([^']+)'\s*,/gm
  let match = linePattern.exec(block)

  while (match) {
    recipes.push({
      recipeKey: match[1],
      zhName: match[2],
    })
    match = linePattern.exec(block)
  }

  return recipes
}

function normalizeImageName(fileName) {
  return path.basename(fileName, path.extname(fileName)).trim()
}

function publicObjectUrl(supabaseUrl, bucket, objectPath) {
  return `${supabaseUrl.replace(/\/$/, '')}/storage/v1/object/public/${bucket}/${objectPath}`
}

function main() {
  const sourceDir = requireArg('--source')
  const seedPath = readArg('--seed', DEFAULT_SEED_PATH)
  const outDir = readArg('--out', DEFAULT_OUT_DIR)
  const bucket = readArg('--bucket', DEFAULT_BUCKET)
  const prefix = readArg('--prefix', DEFAULT_PREFIX).replace(/^\/+|\/+$/g, '')
  const env = parseEnvFile('.env')
  const supabaseUrl = readArg('--supabase-url', env.EXPO_PUBLIC_SUPABASE_URL)

  if (!supabaseUrl) {
    throw new Error('Missing Supabase URL. Pass --supabase-url or set EXPO_PUBLIC_SUPABASE_URL in .env.')
  }

  if (!fs.existsSync(sourceDir)) {
    throw new Error(`Source directory does not exist: ${sourceDir}`)
  }

  const recipes = parseRecipes(seedPath)
  const recipeByZhName = new Map(recipes.map((recipe) => [recipe.zhName, recipe]))
  const files = fs.readdirSync(sourceDir)
    .filter((fileName) => fileName.toLowerCase().endsWith('.png'))
    .sort((a, b) => a.localeCompare(b, 'zh-Hans-CN'))

  const matched = []
  const unmatchedFiles = []

  for (const fileName of files) {
    const imageName = normalizeImageName(fileName)
    const recipe = recipeByZhName.get(imageName)

    if (!recipe) {
      unmatchedFiles.push(fileName)
      continue
    }

    const objectPath = `${prefix}/${recipe.recipeKey}.png`
    matched.push({
      ...recipe,
      fileName,
      localPath: path.resolve(sourceDir, fileName),
      objectPath,
      imageUrl: publicObjectUrl(supabaseUrl, bucket, objectPath),
    })
  }

  fs.mkdirSync(outDir, { recursive: true })

  const runImportScript = [
    '# Generated by scripts/prepare-recipe-image-import.js',
    '# Set SUPABASE_SERVICE_ROLE_KEY in this shell before running.',
    '$ErrorActionPreference = "Stop"',
    `node scripts/import-recipe-images.js --source '${sourceDir.replace(/'/g, "''")}' --bucket '${bucket}' --prefix '${prefix}'`,
    '',
  ].join('\r\n')

  const sqlValues = matched.map((item) => (
    `  ('${escapeSql(item.recipeKey)}', '${escapeSql(item.imageUrl)}')`
  )).join(',\n')

  const updateSql = [
    '-- Generated by scripts/prepare-recipe-image-import.js',
    '-- Updates only recipes that have a matched local image.',
    'with image_rows(recipe_key, image_url) as (',
    '  values',
    sqlValues,
    ')',
    'update public.recipes as recipes',
    'set',
    '  card_image_url = image_rows.image_url,',
    '  cover_image_url = image_rows.image_url,',
    '  updated_at = now()',
    'from image_rows',
    'where recipes.recipe_key = image_rows.recipe_key;',
    '',
  ].join('\n')

  const manifest = [
    'recipe_key,zh_name,file_name,object_path,image_url',
    ...matched.map((item) => [
      item.recipeKey,
      item.zhName,
      item.fileName,
      item.objectPath,
      item.imageUrl,
    ].map((value) => `"${String(value).replace(/"/g, '""')}"`).join(',')),
    '',
  ].join('\n')

  fs.writeFileSync(path.join(outDir, 'run-import-recipe-images.ps1'), runImportScript, 'utf8')
  fs.writeFileSync(path.join(outDir, 'update-recipe-image-urls.sql'), updateSql, 'utf8')
  fs.writeFileSync(path.join(outDir, 'recipe-image-manifest.csv'), manifest, 'utf8')
  fs.writeFileSync(path.join(outDir, 'unmatched-files.txt'), `${unmatchedFiles.join('\n')}${unmatchedFiles.length ? '\n' : ''}`, 'utf8')

  const matchedRecipeKeys = new Set(matched.map((item) => item.recipeKey))
  const missingRecipes = recipes.filter((recipe) => !matchedRecipeKeys.has(recipe.recipeKey))

  console.log(JSON.stringify({
    sourceDir,
    outDir,
    totalRecipes: recipes.length,
    imageFiles: files.length,
    matched: matched.length,
    unmatchedFiles,
    missingRecipeCount: missingRecipes.length,
    runImportScript: path.join(outDir, 'run-import-recipe-images.ps1'),
    updateSql: path.join(outDir, 'update-recipe-image-urls.sql'),
    manifest: path.join(outDir, 'recipe-image-manifest.csv'),
  }, null, 2))

  if (unmatchedFiles.length > 0) {
    process.exitCode = 1
  }
}

try {
  main()
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error))
  process.exit(1)
}
